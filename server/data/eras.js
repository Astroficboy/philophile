export function eraForYear(year) {
  if (year == null || Number.isNaN(year)) return null;
  const found = ERAS.find((e) => year >= e.start && year < e.end);
  if (found) return found;
  return year < ERAS[0].start ? ERAS[0] : ERAS[ERAS.length - 1];
}

